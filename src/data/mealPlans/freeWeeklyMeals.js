export const FREE_CALORIE_HINT = '~1,800 kcal recommended';

export const DAY_NAMES_BY_INDEX = [
  'Sunday',
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
];

export function dayNameToIndex(dayName) {
  const idx = DAY_NAMES_BY_INDEX.indexOf(dayName);
  return idx >= 0 ? idx : new Date().getDay();
}

export function sumDayCalories(dayMeals) {
  if (!dayMeals) return 0;
  return ['breakfast', 'lunch', 'dinner', 'snack'].reduce(
    (sum, key) => sum + (dayMeals[key]?.cal ?? 0),
    0,
  );
}
